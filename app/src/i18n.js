  // Sprache: in den Einstellungen gewählt, sonst nach Systemsprache
  let chosen = null;
  try {
    chosen = JSON.parse(localStorage.getItem("archiver.lang"));
  } catch (e) {}
  const lang = MESSAGES[chosen] ? chosen : (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en";
  const dict = MESSAGES[lang];

  function t(key, vars) {
    let text = dict[key] ?? MESSAGES.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
    return text;
  }

  // Erscheinungsbild: "system" | "light" | "dark", gilt für App und Betrachter
  const darkQuery = global.matchMedia ? global.matchMedia("(prefers-color-scheme: dark)") : null;
  function theme() {
    try {
      const v = JSON.parse(localStorage.getItem("archiver.theme"));
      if (v === "light" || v === "dark") return v;
    } catch (e) {}
    return "system";
  }
  function applyTheme() {
    const v = theme();
    const light = v === "light" || (v === "system" && darkQuery && !darkQuery.matches);
    document.documentElement.classList.toggle("light", light);
    // Fensterrahmen und Glas (lib.rs set_appearance); im Browser-Test fehlt Tauri
    const tauri = global.__TAURI__;
    if (tauri && tauri.core) tauri.core.invoke("set_appearance", { light }).catch(() => {});
  }
  function setTheme(v) {
    try {
      localStorage.setItem("archiver.theme", JSON.stringify(v));
    } catch (e) {}
    applyTheme();
  }
  applyTheme();
  if (darkQuery) darkQuery.addEventListener("change", applyTheme);
  global.addEventListener("storage", (e) => {
    if (e.key === "archiver.theme") applyTheme();
  });

